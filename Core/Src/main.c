/* USER CODE END Header_StartListenUART */
void StartListenUART(void *argument)
{
  /* USER CODE BEGIN StartListenUART */
  /* Infinite loop */

  uint8_t msg[] = "Hello world\r\n";   /* the CR+LF pair moves the cursor to the next line */

  for(;;)
  {
    HAL_UART_Transmit(&hlpuart1, msg, strlen((char *)msg), 1000);
    osDelay(1000);
  }
  /* USER CODE END StartListenUART */
}

